import os
from dotenv import load_dotenv
from langchain_groq import ChatGroq
from pydantic import BaseModel, Field
from langchain_core.messages import AIMessage, HumanMessage, SystemMessage


load_dotenv(override=True)


class Grade(BaseModel):
    """Evaluate the tool calls of the agent"""
    reasoning: str = Field(..., description="Explain your reasoning for whether the tool call is correct or not.")
    is_correct: bool = Field(..., description="True if the tool call is correct according to the criteria, otherwise False.")

grader_instructions = """You are an evaluation assistant for Infomary, the AI Senior Care Advisor agent for InfoSenior.care.

Output only **VALID** JSON.

Your work is to evaluate an agent's tool call parameters. You will be given a user's prompt and a dictionary of tool call arguments generated by a model.

The agent has exactly two tools:
- facility_search(facility_type, city, state, descriptive_text) -- all four fields are optional and should be left blank ("") when the user didn't mention that information.
- google_search(query) -- a free-text web search query, used for lookups that aren't about finding a facility.

Here is the evaluation criteria to follow:
1) Ensure that all tool call parameters are grounded in the user's prompt and nothing is inferred by the model itself. Hallucinations and wrong tool parameters are not allowed.
2) It is OK if the following parameters do not exactly match the information in the user's prompt char-by-char but do mean the same thing, including obvious typo/abbreviation corrections:
    • facility_type
    • city
    • state
    • descriptive_text
For example, user asks "need a nurshing home near tuscon az" and the model generates {{facility_type: "nursing home", city: "Tucson", state: "AZ"}}. Or the user says "forgets to take meds" and the model generates {{descriptive_text: "medication management"}} -- a reasonable restatement of a described need, not an invention.
The model might automatically make common sense corrections and handle typos so they are acceptable.
Note: Don't account for bigger divergence between the user's prompt and the generated output. For example, if the user only says "my mom keeps forgetting things" (no facility type named) and the model generates {{facility_type: "memory care"}}, that is inventing a category the user never named -- not acceptable.
3) A blank ("") field is always safe/correct for facility_search when the user didn't mention that piece of information -- do not penalize blanks.
4) query (google_search) is a semantic web-search parameter. It should be semantically related to the user's prompt and should not contain any information that the user didn't ask for or that wasn't present in the user's prompt.

Correctness:
True means that the tool call meets all of the criteria.
False means that the tool call does not meet all of the criteria.

Explain your reasoning in a step-by-step manner to ensure your reasoning and conclusion are correct
"""

lead_gen_grader_instructions = """You are an evaluation assistant for Infomary, the AI Senior Care Advisor agent for InfoSenior.care.

Output only **VALID** JSON.

Infomary follows a 5-phase conversion flow, always in order, never skipping ahead:
  Phase 1 -- Emotion first: acknowledge the user's feeling and normalize it before anything else.
  Phase 2 -- Expert insight: share one relevant insight tied to their situation.
  Phase 3 -- Soft recommendation + permission: suggest a care type and ask permission to explore options -- never collect details before this permission is given.
  Phase 4 -- Natural detail collection: only after a yes, collect details (location, age, living situation, medical condition, budget) ONE AT A TIME, always explaining why before asking.
  Phase 5 -- Contact capture: only after the user separately agrees to "personal support" from a care advisor, ask for a phone number or email naturally (e.g. "What's the best number or email to contact you?"), never coldly (e.g. never "Can I have your phone number?" or "I need your email to proceed").

It also follows these rules:
- Never ask more than one question in a single reply.
- Never ask for contact info before value has been provided AND permission for personal support has been separately given -- a "yes" to exploring options is NOT the same as permission to be contacted.
- Every question must explain WHY it's being asked, not feel like a cold form.
- Objections ("just looking", "can't afford it", "need to think about it", "we're managing at home") should be met with empathy and reassurance (e.g. the service is free, no pressure, Medicaid/Medicare accepted), not ignored or pushed past.
- Never diagnose a medical condition -- suggest discussing it with a doctor instead.
- Never pressure the user, and never make the user feel like they're filling out a form.
- A plain greeting ("hi", "hello", "how are you") does not require any of the phases -- a warm, brief greeting back is correct; jumping straight into Phase 1/asking for details on a bare greeting is not.

You will be given the user's message and the agent's reply. Evaluate whether the reply is CORRECT:
1. It does not skip ahead of where the conversation would reasonably be in the flow (e.g. it must not ask for contact info out of nowhere on a first message, or on a message that hasn't given permission for personal support).
2. It asks at most ONE question, and briefly explains why if it does.
3. If the user raised an objection, the reply addresses it with empathy and reassurance rather than ignoring it or pushing forward regardless.
4. It doesn't diagnose a medical condition or pressure the user.

Explain your reasoning in a step-by-step manner to ensure your reasoning and conclusion are correct.
"""
GROQ_API_KEY = os.getenv('GROQ_API_KEY')

if not GROQ_API_KEY:
    raise ValueError("GROQ API Key is missing!")

llm = ChatGroq(
    api_key=GROQ_API_KEY,
    model='openai/gpt-oss-20b',
    temperature=0
)

evaluator_llm = llm.with_structured_output(Grade, method="json_schema")


valid_tool_order = ["facility_search", "google_search"]
tool_rank = {name: i for i, name in enumerate(valid_tool_order)}

async def agent_trajectory_correctness(inputs: dict, outputs:dict) -> list[dict]:
    "Evaluates the agent's complete trajectory"

    CorrectToolNames = CorrectToolArguments = CorrectToolOrder = True
    grading_errors = []

    called_tool_names = []
    for message in outputs["messages"]:
        if isinstance(message, AIMessage):
            for tool_call in message.tool_calls:
                called_tool_names.append({"name": tool_call["name"], "args": tool_call["args"]})

    if called_tool_names:
        CorrectToolNames = all(tool['name'] in tool_rank for tool in called_tool_names)

        ranks = [tool_rank[tool['name']] for tool in called_tool_names if tool['name'] in tool_rank]

        CorrectToolOrder = all(ranks[i] <= ranks[i + 1] for i in range(len(ranks) - 1))

        correctness = []

        for tool in called_tool_names:

            user_message = f"""USER PROMPT: {inputs['question']}
            TOOL CALL: {tool['name']}({tool['args']})
            """
            try:
                grade: Grade = await evaluator_llm.ainvoke([SystemMessage(grader_instructions), HumanMessage(user_message)])
            except Exception as e:
                grading_errors.append({"tool": tool.get("name"), "error": str(e)})
                continue
            correctness.append(grade.is_correct)

        CorrectToolArguments = all(correctness) if correctness else True

    results = [
        {"key": "toolNameCorrectness", "score": CorrectToolNames},
        {"key": "toolOrderCorrectness", "score": CorrectToolOrder},
        {"key": "toolArgsCorrectness", "score": CorrectToolArguments},
        {"key": "toolArgsGradingErrors", "score": len(grading_errors)},
    ]

    # lead-generation behavior -- grades the agent's final reply against the
    # 5-phase flow / anti-interrogation / objection-handling rules. Runs
    # regardless of whether a tool was called this turn, since phase/tone
    # rules apply to every reply, not just ones that hit facility_search or
    # google_search.
    final_text = ""
    for message in reversed(outputs["messages"]):
        if isinstance(message, AIMessage) and message.content:
            final_text = message.content
            break

    lead_gen_grading_errors = 0

    if final_text:
        lead_gen_message = f"""USER MESSAGE: {inputs['question']}
        AGENT REPLY: {final_text}
        """
        try:
            lead_gen_grade: Grade = await evaluator_llm.ainvoke(
                [SystemMessage(lead_gen_grader_instructions), HumanMessage(lead_gen_message)]
            )
            results.append({
                "key": "leadGenCorrectness",
                "score": lead_gen_grade.is_correct,
                "comment": lead_gen_grade.reasoning,
            })
        except Exception as e:
            lead_gen_grading_errors += 1
            results.append({"key": "leadGenCorrectness", "score": True, "comment": f"grading error, not scored: {e}"})
    else:
        results.append({"key": "leadGenCorrectness", "score": True, "comment": "no final text to grade"})

    results.append({"key": "leadGenGradingErrors", "score": lead_gen_grading_errors})

    return results
